import { ApiProperty, ApiPropertyOptional } from "@nestjs/swagger";
import {
  IsNotEmpty,
  IsOptional,
  IsString,
  Length,
  Matches,
  MaxLength,
} from "class-validator";

export class EnableMfaDto {
  @ApiProperty({
    example: "123456",
    description: "6-digit TOTP code generated by authenticator app",
  })
  @IsString()
  @IsNotEmpty()
  @Length(6, 6, { message: "TOTP code must be 6 digits" })
  @Matches(/^\d{6}$/, { message: "TOTP code must be 6 digits" })
  totpCode!: string;
}

export class VerifyMfaLoginDto {
  @ApiProperty({ description: "Temporary 2FA token returned during login" })
  @IsString()
  @IsNotEmpty()
  @MaxLength(2048)
  mfaToken!: string;

  @ApiPropertyOptional({ example: "123456", description: "6-digit TOTP code" })
  @IsOptional()
  @IsString()
  @Matches(/^\d{6}$/, { message: "TOTP code must be 6 digits" })
  totpCode?: string;

  @ApiPropertyOptional({
    example: "A1B2-C3D4-E5F6-7890-ABCD-EF01",
    description:
      "Single-use backup recovery code, 24 hex characters in six groups of four",
  })
  @IsOptional()
  @IsString()
  @Matches(/^[A-F0-9]{4}(?:-[A-F0-9]{4}){5}$/i, {
    message: "Recovery code has an invalid format",
  })
  recoveryCode?: string;
}

export class DisableMfaDto {
  @ApiProperty({ description: "User account password" })
  @IsString()
  @IsNotEmpty()
  @MaxLength(256)
  password!: string;

  @ApiPropertyOptional({ example: "123456", description: "6-digit TOTP code" })
  @IsOptional()
  @IsString()
  @Length(6, 6, { message: "TOTP code must be 6 digits" })
  @Matches(/^\d{6}$/, { message: "TOTP code must be 6 digits" })
  totpCode?: string;

  @ApiPropertyOptional({
    example: "A1B2-C3D4-E5F6-7890-ABCD-EF01",
    description:
      "Single-use backup recovery code, same shape as `/auth/mfa/enable` issued it",
  })
  @IsOptional()
  @IsString()
  @Matches(/^[A-F0-9]{4}(?:-[A-F0-9]{4}){5}$/i, {
    message: "Recovery code has an invalid format",
  })
  recoveryCode?: string;
}

export class MfaSecretResponseDto {
  @ApiProperty({
    example: "JBSWY3DPEHPK3PXP",
    description: "Base32 secret key",
  })
  secret!: string;

  @ApiProperty({
    example:
      "otpauth://totp/Allinone:user@example.com?secret=JBSWY3DPEHPK3PXP&issuer=Allinone",
  })
  otpauthUrl!: string;

  @ApiProperty({ example: "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAA..." })
  qrCodeDataUrl!: string;
}

export class MfaEnableResponseDto {
  @ApiProperty({
    example: ["A1B2-C3D4-E5F6-7890-ABCD-EF01", "0123-4567-89AB-CDEF-0123-4567"],
    description:
      "Ten single-use recovery codes, 96 bits each (save these securely — only their keyed digests are stored)",
  })
  recoveryCodes!: string[];
}
